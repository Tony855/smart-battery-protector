-- Voltage is V (0.001 V resolution); current is A (0.001 A resolution).
-- Temperature is an integer count of 0.1°C: 253 represents 25.3°C.
CREATE TABLE IF NOT EXISTS device_telemetry (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  device_id BIGINT NOT NULL REFERENCES devices(id),
  sample_uuid UUID NOT NULL,
  observed_at TIMESTAMPTZ(3) NOT NULL,
  battery_voltage_v NUMERIC(6,3) NOT NULL CHECK (battery_voltage_v BETWEEN 0 AND 60),
  battery_current_a NUMERIC(9,3) CHECK (battery_current_a BETWEEN -1000 AND 1000),
  temperature_deci_c SMALLINT CHECK (temperature_deci_c BETWEEN -500 AND 2000),
  state_code VARCHAR(16) NOT NULL
    CHECK (state_code IN ('normal','charging','discharging','protected','fault','unknown')),
  engine_running VARCHAR(7) NOT NULL DEFAULT 'unknown'
    CHECK (engine_running IN ('yes','no','unknown')),
  received_at TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UNIQUE (device_id, sample_uuid)
);
CREATE INDEX IF NOT EXISTS idx_device_telemetry_time
  ON device_telemetry(device_id, observed_at DESC);
