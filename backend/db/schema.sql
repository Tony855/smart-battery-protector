-- Smart Battery Protector PostgreSQL schema snapshot (PostgreSQL 15+).
-- Canonical incremental migrations: backend/db/postgresql/migrations/*.sql
CREATE TABLE IF NOT EXISTS users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  auth_subject VARCHAR(191) NOT NULL UNIQUE,
  status VARCHAR(16) NOT NULL DEFAULT 'active' CHECK (status IN ('active','locked','deleted')),
  created_at TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS product_models (
  model_id VARCHAR(48) PRIMARY KEY,
  family VARCHAR(8) NOT NULL CHECK (family IN ('main','aux')),
  connectivity VARCHAR(16)[] NOT NULL,
  voltage_capability VARCHAR(8)[] NOT NULL,
  config_schema_version INTEGER NOT NULL DEFAULT 1 CHECK (config_schema_version > 0),
  created_at TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS devices (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  serial_number VARCHAR(64) NOT NULL UNIQUE,
  model_id VARCHAR(48) NOT NULL REFERENCES product_models(model_id),
  hw_revision VARCHAR(32), fw_version VARCHAR(64),
  last_seen_at TIMESTAMPTZ(3),
  lifecycle_status VARCHAR(16) NOT NULL DEFAULT 'provisioning'
    CHECK (lifecycle_status IN ('provisioning','active','suspended','retired')),
  created_at TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_devices_last_seen ON devices(last_seen_at);
CREATE TABLE IF NOT EXISTS device_bindings (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  device_id BIGINT NOT NULL REFERENCES devices(id),
  user_id BIGINT NOT NULL REFERENCES users(id),
  role VARCHAR(8) NOT NULL CHECK (role IN ('owner','admin','viewer')),
  bound_at TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  revoked_at TIMESTAMPTZ(3)
);
CREATE INDEX IF NOT EXISTS idx_binding_device_active ON device_bindings(device_id, revoked_at);
CREATE INDEX IF NOT EXISTS idx_binding_user_active ON device_bindings(user_id, revoked_at);
CREATE TABLE IF NOT EXISTS device_configurations (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  device_id BIGINT NOT NULL REFERENCES devices(id),
  revision BIGINT NOT NULL CHECK (revision > 0),
  schema_version INTEGER NOT NULL CHECK (schema_version > 0),
  profile_id VARCHAR(64) NOT NULL,
  payload JSONB NOT NULL,
  updated_at TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UNIQUE (device_id, revision)
);
CREATE TABLE IF NOT EXISTS device_events (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  device_id BIGINT NOT NULL REFERENCES devices(id),
  event_uuid UUID NOT NULL,
  event_type VARCHAR(48) NOT NULL, fault_code VARCHAR(48),
  occurred_at TIMESTAMPTZ(3) NOT NULL, details JSONB,
  received_at TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UNIQUE (device_id, event_uuid)
);
CREATE INDEX IF NOT EXISTS idx_device_event_time ON device_events(device_id, occurred_at DESC);
CREATE TABLE IF NOT EXISTS firmware_releases (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  release_id VARCHAR(64) NOT NULL UNIQUE,
  model_id VARCHAR(48) NOT NULL REFERENCES product_models(model_id),
  version VARCHAR(64) NOT NULL, artifact_digest_sha256 CHAR(64) NOT NULL,
  signature_reference VARCHAR(255) NOT NULL,
  rollout_state VARCHAR(16) NOT NULL DEFAULT 'draft'
    CHECK (rollout_state IN ('draft','staged','released','revoked')),
  created_at TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS audit_events (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  actor_type VARCHAR(8) NOT NULL CHECK (actor_type IN ('user','device','admin','system')),
  actor_id VARCHAR(128) NOT NULL, action VARCHAR(96) NOT NULL,
  target_type VARCHAR(48) NOT NULL, target_id VARCHAR(128) NOT NULL,
  result VARCHAR(8) NOT NULL CHECK (result IN ('accepted','rejected','failed')),
  occurred_at TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP, metadata JSONB
);
CREATE INDEX IF NOT EXISTS idx_audit_target ON audit_events(target_type, target_id, occurred_at);
CREATE TABLE IF NOT EXISTS device_credentials (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  device_id BIGINT NOT NULL REFERENCES devices(id),
  key_id VARCHAR(96) NOT NULL UNIQUE, secret_hash CHAR(64),
  public_key_base64 VARCHAR(64), public_key_algorithm VARCHAR(24),
  hash_algorithm VARCHAR(24) NOT NULL DEFAULT 'sha256',
  signature_algorithm VARCHAR(24) NOT NULL DEFAULT 'ed25519',
  credential_status VARCHAR(8) NOT NULL DEFAULT 'active'
    CHECK (credential_status IN ('active','revoked')),
  created_at TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  last_used_at TIMESTAMPTZ(3), revoked_at TIMESTAMPTZ(3)
);
CREATE INDEX IF NOT EXISTS idx_device_credential_active ON device_credentials(device_id, credential_status);
CREATE TABLE IF NOT EXISTS device_claim_codes (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  device_id BIGINT NOT NULL REFERENCES devices(id),
  code_hash CHAR(64) NOT NULL UNIQUE,
  expires_at TIMESTAMPTZ(3) NOT NULL, used_at TIMESTAMPTZ(3),
  created_at TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_claim_device_unused ON device_claim_codes(device_id, used_at, expires_at);
CREATE TABLE IF NOT EXISTS device_telemetry (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  device_id BIGINT NOT NULL REFERENCES devices(id), sample_uuid UUID NOT NULL,
  observed_at TIMESTAMPTZ(3) NOT NULL,
  battery_voltage_v NUMERIC(6,3) NOT NULL CHECK (battery_voltage_v BETWEEN 0 AND 60),
  battery_current_a NUMERIC(9,3) CHECK (battery_current_a BETWEEN -1000 AND 1000),
  temperature_deci_c SMALLINT CHECK (temperature_deci_c BETWEEN -500 AND 2000),
  state_code VARCHAR(16) NOT NULL CHECK (state_code IN ('normal','charging','discharging','protected','fault','unknown')),
  engine_running VARCHAR(7) NOT NULL DEFAULT 'unknown' CHECK (engine_running IN ('yes','no','unknown')),
  received_at TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UNIQUE (device_id, sample_uuid)
);
CREATE INDEX IF NOT EXISTS idx_device_telemetry_time ON device_telemetry(device_id, observed_at DESC);
